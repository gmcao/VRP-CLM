%%  这段代码定义了一个名为 deal0 的函数，它用于计算和选择一个起始点（通常是配送中心或仓库），作为车辆路径的起点。函数考虑了距离成本、时间窗限制和不同时间成本的权重。

%输入：t1, t2, t3 时间成本参数，用于计算时间相关的成本
%输入：a、b       开始、结束时间
%输入：dist       距离矩阵
%输入：cap        载重量
%输入：demands    配送点需求量
%输入: remain     未访问的顾客集合的索引
%输出：plot       选择的起始点的索引
%输出：minCd      选择的起始点对应的最小成本
%输出：time       到达起始点的时间
%输出：ind        在 remain 数组中选择的起始点的索引

function [minCd, plot, time, ind] = deal0(t1, t2, t3, a, b, dist, remain, speed)
Cd = zeros(size(remain, 2), 1); % 创建一个数组 Cd 来存储每个可能起始点的成本

for j = 1:size(remain, 2)
    % 计算配送中心到顾客点的距离
    C1 = dist(1, remain(j) + 1);
    % 计算行驶时间（距离除以速度）
    t1_time = C1 / speed;
    % 计算最晚到达时间，取行驶时间与顾客时间窗开始时间的最大值
    C2 = max(t1_time, a(remain(j)));
    % 计算在时间窗内可用的时间
    C3 = b(remain(j)) - C2;
    % 计算总成本
    C0 = t1 * t1_time + t2 * C2 + t3 * C3;
    Cd(j) = C0;
end

% 使用 min 函数找到 Cd 数组中的最小值和对应的索引
[minCd, ind] = min(Cd);
plot = remain(ind); % 选择的起始点的索引
% 计算到达起始点的时间，取配送中心到起始点的行驶时间与起始点的时间窗开始时间的最大值
time = max(dist(1, plot + 1) / speed, a(plot));
end

